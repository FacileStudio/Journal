const statusLedger = `CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now());
INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true);`

func section(t *testing.T, file, name string) string {
	t.Helper()
	raw, err := fs.ReadFile(migrations.FS, file)
	if err != nil {
		t.Fatalf("read %s: %v", file, err)
	}
	_, after, found := strings.Cut(string(raw), "-- +goose "+name)
	if !found {
		t.Fatalf("%s has no %s section", file, name)
	}
	body, _, _ := strings.Cut(after, "-- +goose ")
	return body
}

func exec(t *testing.T, db *gorm.DB, sql string) {
	t.Helper()
	if err := db.Exec(sql).Error; err != nil {
		t.Fatalf("exec: %v", err)
	}
}

func appliedVersions(t *testing.T, db *gorm.DB) []int64 {
	t.Helper()
	var versions []int64
	if err := db.Raw(`SELECT version_id FROM goose_db_version WHERE version_id > 0 ORDER BY id`).Scan(&versions).Error; err != nil {
		t.Fatalf("read the ledger: %v", err)
	}
	return versions
}

func columnDefault(t *testing.T, db *gorm.DB, table, column string) string {
	t.Helper()
	var value *string
	err := db.Raw(`SELECT column_default FROM information_schema.columns
		WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?`, table, column).Scan(&value).Error
	if err != nil {
		t.Fatalf("read the default of %s.%s: %v", table, column, err)
	}
	if value == nil {
		return ""
	}
	return *value
}

func assertVersions(t *testing.T, db *gorm.DB, want ...int64) {
	t.Helper()
	if got := appliedVersions(t, db); !slices.Equal(got, want) {
		t.Fatalf("applied versions %v, want %v", got, want)
	}
}

// TestUpBuildsAnEmptyDatabase checks an empty schema reaches the latest
// version through every migration in order, and that a second run is a no-op.
func TestUpBuildsAnEmptyDatabase(t *testing.T) {
	db := testdb.Migrated(t)
	assertVersions(t, db, 1, 2)
	if got := columnDefault(t, db, "log_entries", "received_at"); got != "now()" {
		t.Fatalf("log_entries.received_at default %q, want now()", got)
	}
	if err := testdb.Up(db); err != nil {
		t.Fatalf("a second run is not a no-op: %v", err)
	}
	assertVersions(t, db, 1, 2)
}

// TestUpStampsADatabaseBuiltByAutoMigrate rebuilds production's shape, the
// baseline's tables with no ledger and rows in them, and checks Up records
// the baseline without running it, applies the later migrations, and keeps
// the rows. Running the baseline would fail on its first CREATE TABLE.
func TestUpStampsADatabaseBuiltByAutoMigrate(t *testing.T) {
	assertStampsLegacy(t, "")
}

// TestUpStampsALegacyDatabaseAfterStatus covers an operator who ran
// `migrate status` before the first boot: goose then created the ledger with
// only its version 0 sentinel, and the baseline must still be stamped rather
// than run.
func TestUpStampsALegacyDatabaseAfterStatus(t *testing.T) {
	assertStampsLegacy(t, statusLedger)
}

func assertStampsLegacy(t *testing.T, ledger string) {
	t.Helper()
	db := testdb.Open(t)
	if ledger != "" {
		exec(t, db, ledger)
	}
	exec(t, db, section(t, "00001_baseline.sql", "Up"))
	exec(t, db, `INSERT INTO users (email, name, created_at) VALUES ('ada@facile.studio', 'Ada', '2026-01-02T03:04:05Z');
		INSERT INTO log_entries (app, message, created_at, received_at) VALUES ('nuage', 'upload failed', '2026-01-02T03:04:05Z', '2026-01-02T03:04:06Z')`)
	if columnDefault(t, db, "log_entries", "received_at") != "" {
		t.Fatal("the legacy schema already has the defaults migration")
	}

	if err := testdb.Up(db); err != nil {
		t.Fatalf("up on a legacy database: %v", err)
	}
	assertVersions(t, db, 1, 2)
	if got := columnDefault(t, db, "log_entries", "received_at"); got != "now()" {
		t.Fatalf("log_entries.received_at default %q, want now()", got)
	}
	var kept []string
	err := db.Raw(`SELECT name FROM users WHERE email = 'ada@facile.studio'
		UNION ALL SELECT message FROM log_entries WHERE search @@ to_tsquery('simple', 'upload')`).Scan(&kept).Error
	if err != nil {
		t.Fatalf("read the rows: %v", err)
	}
	if !slices.Equal(kept, []string{"Ada", "upload failed"}) {
		t.Fatalf("the existing rows changed: %q", kept)
	}
}

// TestUpRefusesADatabaseOlderThanTheBaseline checks a schema without the
// tables v0.4.0 added is refused rather than stamped: stamping would record
// DDL the database never ran, and nothing would ever run it.
func TestUpRefusesADatabaseOlderThanTheBaseline(t *testing.T) {
	db := testdb.Open(t)
	exec(t, db, `CREATE TABLE users (id bigserial PRIMARY KEY, email text NOT NULL)`)
	if err := testdb.Up(db); !errors.Is(err, migrations.ErrPredatesBaseline) {
		t.Fatalf("up on a pre-v0.4.0 database = %v, want ErrPredatesBaseline", err)
	}
	var ledger *string
	if err := db.Raw(`SELECT to_regclass('goose_db_version')::text`).Scan(&ledger).Error; err != nil {
		t.Fatalf("look for the ledger: %v", err)
	}
	if ledger != nil {
		t.Fatal("a refused database was given a ledger")
	}
}

// TestTheDefaultsMigrationGoesDownAndUp runs 00002's Down and Up by hand on a
// migrated database, which is the rollback the changelog describes.
func TestTheDefaultsMigrationGoesDownAndUp(t *testing.T) {
	db := testdb.Migrated(t)
	columns := [][2]string{
		{"alert_rules", "created_at"}, {"api_keys", "created_at"}, {"log_entries", "created_at"},
		{"log_entries", "received_at"}, {"saved_queries", "created_at"}, {"source_maps", "created_at"},
	}
	for _, step := range []struct{ name, want string }{{"Down", ""}, {"Up", "now()"}} {
		exec(t, db, section(t, "00002_timestamp_defaults.sql", step.name))
		for _, column := range columns {
			if got := columnDefault(t, db, column[0], column[1]); got != step.want {
				t.Fatalf("after %s, %s.%s default %q, want %q", step.name, column[0], column[1], got, step.want)
			}
		}
	}
}

// TestDeletingAUserRevokesItsSessions checks porte's tables key on Journal's
// users, not on porte_users, so deleting an account takes its sessions and
// its identity link with it.
func TestDeletingAUserRevokesItsSessions(t *testing.T) {
	db := testdb.Migrated(t)
	exec(t, db, `INSERT INTO users (id, email, name, password_hash, is_admin, created_at)
		VALUES (1, 'someone@facile.studio', 'Someone', '', false, now());
		INSERT INTO porte_sessions (token_hash, user_id, expires_at) VALUES ('t', 1, now() + interval '1 day');
		INSERT INTO porte_identities (user_id, provider, subject) VALUES (1, 'https://sso.test/', 'abc');
		DELETE FROM users WHERE id = 1`)
	for _, table := range []string{"porte_sessions", "porte_identities"} {
		var remaining int64
		if err := db.Raw(`SELECT count(*) FROM ` + table).Scan(&remaining).Error; err != nil {
			t.Fatalf("count %s: %v", table, err)
		}
		if remaining != 0 {
			t.Fatalf("%s survived the user it belongs to", table)
		}
	}
}

func describe(t *testing.T, db *gorm.DB, table string) []string {
	t.Helper()
	var schema string
	var shape []string
	if err := db.Raw(`SELECT current_schema()`).Scan(&schema).Error; err != nil {
		t.Fatalf("current schema: %v", err)
	}
	err := db.Raw(`SELECT column_name || ' ' || data_type || ' ' || is_nullable || ' ' || coalesce(column_default, '')
		FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?
		UNION ALL SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?`, table, table).Scan(&shape).Error
	if err != nil {
		t.Fatalf("describe %s: %v", table, err)
	}
	for i := range shape {
		shape[i] = strings.ReplaceAll(shape[i], schema+".", "")
	}
	slices.Sort(shape)
	return shape
}

func assertSameShape(t *testing.T, table, library string, got, want []string) {
	t.Helper()
	if !slices.Equal(got, want) {
		t.Errorf("%s in the baseline =\n%s\nwant %s's\n%s", table, strings.Join(got, "\n"), library, strings.Join(want, "\n"))
	}
}

// TestLibrarySchemasAreInTheBaseline checks the baseline holds, column for
// column and index for index, the tables Journal used to create at every boot
// from library DDL: porte's identity tables (whose foreign keys Journal points
// at its own users), tronc/mcp's PendingSchema and antenne-client's outbox.
// A library bump that changes one of them fails here, and the change then
// needs a numbered migration of its own.
func TestLibrarySchemasAreInTheBaseline(t *testing.T) {
	antenneUp, _, _ := strings.Cut(strings.SplitN(outbox.Migration, "-- +goose Up", 2)[1], "-- +goose Down")
	libraries := []struct {
		name   string
		ddl    string
		tables []string
	}{
		{"porte", portepg.Schema, []string{"porte_identities", "porte_sessions", "porte_login_codes"}},
		{"mcp", mcpkit.PendingSchema, []string{"mcp_actions"}},
		{"antenne", antenneUp, []string{"antenne_outbox"}},
	}
	migrated := testdb.Migrated(t)
	for _, library := range libraries {
		t.Run(library.name, func(t *testing.T) {
			db := testdb.Open(t)
			exec(t, db, library.ddl)
			for _, table := range library.tables {
				assertSameShape(t, table, library.name, describe(t, migrated, table), describe(t, db, table))
			}
		})
	}
}
